"""生成 3 个新规划的种子 SQL（roadmap_id=2/3/4）。
每个规划 90 天 × 每天 4 条任务（am理论 / pm实战 / ev复盘 / extra素材/表达）。
运行: python gen_new_seeds.py  → 生成 seed_ai_eng.sql / seed_selfmedia.sql / seed_crossborder.sql
"""
import os

# ---------- 公共：SQL 转义 ----------
def esc(s):
    return s.replace("\\", "\\\\").replace("'", "''")

# ---------- 通用生成器 ----------
def gen_sql(rid, days):
    """days: [(day_no, week_no, stage, theme, output, [(slot, slot_name, content), ...]), ...]"""
    lines = []
    for day_no, week_no, stage, theme, output, todos in days:
        lines.append(
            f"INSERT INTO plan_days (roadmap_id, day_no, week_no, stage, theme, output) "
            f"VALUES ({rid}, {day_no}, {week_no}, {stage}, '{esc(theme)}', '{esc(output)}');"
        )
        for slot, slot_name, content in todos:
            lines.append(
                f"INSERT INTO todos (roadmap_id, day_no, slot, slot_name, content, done) "
                f"VALUES ({rid}, {day_no}, '{slot}', '{esc(slot_name)}', '{esc(content)}', 0);"
            )
    return "\n".join(lines) + "\n"


