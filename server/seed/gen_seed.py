def gen_sql():
    lines = ["SET NAMES utf8mb4;", "USE roadmap;", "TRUNCATE TABLE todos;", "TRUNCATE TABLE plan_days;"]
    for d in DAYS:
        lines.append(
            f"INSERT INTO plan_days (day_no, week_no, stage, theme, output) "
            f"VALUES ({d['day']}, {d['week']}, {d['stage']}, '{esc(d['theme'])}', '{esc(d['output'])}');"
        )
    for d in DAYS:
        day = d["day"]
        for slot, content in d["todos"]:
            lines.append(
                f"INSERT INTO todos (day_no, slot, slot_name, content, done) "
                f"VALUES ({day}, '{slot}', '{SLOT_NAMES[slot]}', '{esc(content)}', 0);"
            )
    return "\n".join(lines)

def esc(s):
    return s.replace("\\", "\\\\").replace("'", "''")

